export function getPopulatedAirports(notams: AirportNotam[] = INITIAL_SOUTH_AFRICAN_NOTAMS): SouthAfricanAirport[] {
  return SOUTH_AFRICAN_AIRPORTS.map((apt) => {
    const aptNotams = notams.filter((n) => n.airportIcao === apt.icao);
    let highestSeverity: SouthAfricanAirport['highestSeverity'] = 'INFO';
    if (aptNotams.some((n) => n.severity === 'CRITICAL')) {
      highestSeverity = 'CRITICAL';
    } else if (aptNotams.some((n) => n.severity === 'WARNING')) {
      highestSeverity = 'WARNING';
    } else if (aptNotams.some((n) => n.severity === 'ADVISORY')) {
      highestSeverity = 'ADVISORY';
    }

    return {
      ...apt,
      activeNotams: aptNotams,
      activeNotamCount: aptNotams.length,
      highestSeverity,
    };
  });
}

